import mongoose from "mongoose";
import Trip from "../models/Trip.js";
import { generateItinerary } from "../services/ai/gemini.service.js";
import { itinerarySchema } from "../validators/itinerary.validator.js";

export const generateTripItinerary = async (req, res) => {
  try {
    // Step 1: Get trip ID from URL
    const { tripId } = req.params;

    // Step 2: Validate MongoDB ID
    if (!mongoose.Types.ObjectId.isValid(tripId)) {
      return res.status(400).json({
        success: false,
        message: "Invalid trip ID.",
      });
    }

    // Step 3: Find trip belonging to logged-in user
    const trip = await Trip.findOne({
      _id: tripId,
      userId: req.user._id,
    });

    if (!trip) {
      return res.status(404).json({
        success: false,
        message: "Trip not found.",
      });
    }

    // Step 4: Generate itinerary using Gemini
    const result = await generateItinerary(trip);

    // Step 5: Validate Gemini response using Zod
    const validationResult = itinerarySchema.safeParse(result);

    if (!validationResult.success) {
      console.error(
      "Invalid itinerary generated by Gemini:",
      validationResult.error.issues
    );

    return res.status(422).json({
    success: false,
    message: "Gemini generated an invalid itinerary.",
    errors: validationResult.error.issues,
    });
}

// Step 6: Save validated itinerary in MongoDB
trip.itinerary = validationResult.data.itinerary;

await trip.save();

// Step 7: Return saved itinerary
return res.status(200).json({
  success: true,
  message: "Itinerary generated and saved successfully.",
  itinerary: trip.itinerary,
});     
    

  } catch (error) {
    console.error("Itinerary Generation Error:", error);

    return res.status(500).json({
      success: false,
      message: "Failed to generate itinerary.",
      error: error.message,
    });
  }
};