// Update existing itinerary
export const updateTripItinerary = async (req, res) => {
  try {
    const { tripId } = req.params;

    // Validate Trip ID
    if (!mongoose.Types.ObjectId.isValid(tripId)) {
      return res.status(400).json({
        success: false,
        message: "Invalid trip ID."
      });
    }

    // Validate incoming itinerary
    const validationResult = itinerarySchema.safeParse(req.body);

    if (!validationResult.success) {
      return res.status(422).json({
        success: false,
        message: "Invalid itinerary data.",
        errors: validationResult.error.issues
      });
    }

    // Find trip belonging to logged-in user
    const trip = await Trip.findOne({
      _id: tripId,
      userId: req.user._id
    });

    if (!trip) {
      return res.status(404).json({
        success: false,
        message: "Trip not found."
      });
    }

    // Replace existing itinerary
    trip.itinerary = validationResult.data.itinerary;

    await trip.save();

    return res.status(200).json({
      success: true,
      message: "Itinerary updated successfully.",
      itinerary: trip.itinerary
    });

  } catch (error) {
    console.error("Update itinerary error:", error);

    return res.status(500).json({
      success: false,
      message: "Failed to update itinerary.",
      error: error.message
    });
  }
};

